/**
 * Compose final preset registry + manifest from RVE + Bits catalogs.
 * Shared by vendor-rve-presets.cjs and vendor-bits-presets.cjs.
 */
const fs = require("node:fs");
const path = require("node:path");
const { RVE_PRESET_CATALOG } = require("./rve-preset-catalog.cjs");
const { BITS_PRESET_CATALOG } = require("./bits-preset-catalog.cjs");

const ROOT = path.resolve(__dirname, "..");
const PRESETS_DIR = path.join(ROOT, "resources/presets");
const RENDERER_DATA_DIR = path.join(ROOT, "src/renderer/src/data/presets");
const REGISTRY_PATH = path.join(
  ROOT,
  "resources/templates/default-project/subprojects/default/remotion/src/presets/registry.ts"
);
const BITS_DIR = path.join(
  ROOT,
  "resources/templates/default-project/subprojects/default/remotion/src/presets/bits"
);

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function bitsVendored() {
  return (
    fs.existsSync(path.join(BITS_DIR, "index.ts")) &&
    BITS_PRESET_CATALOG.every((item) => fs.existsSync(path.join(BITS_DIR, item.file)))
  );
}

function buildRveManifestEntries() {
  return RVE_PRESET_CATALOG.map((item) => {
    const moduleBase = item.file.replace(/\.tsx$/, "");
    return {
      id: item.id,
      name: item.name,
      description: item.description,
      category: item.category,
      kind: "component",
      component: item.component,
      modulePath: `presets/rve/${moduleBase}`,
      durationInFrames: item.durationInFrames,
      isBuiltin: true,
      thumbnail: null,
      parameters: [],
      license: "MIT",
      source: "reactvideoeditor/remotion-templates",
    };
  });
}

function buildBitsManifestEntries() {
  if (!bitsVendored()) return [];
  return BITS_PRESET_CATALOG.map((item) => {
    const moduleBase = item.file.replace(/\.tsx$/, "");
    return {
      id: item.id,
      name: item.name,
      description: item.description,
      category: item.category,
      kind: "component",
      component: item.component,
      modulePath: `presets/bits/${moduleBase}`,
      durationInFrames: item.durationInFrames,
      isBuiltin: true,
      thumbnail: null,
      parameters: [],
      license: "MIT",
      source: "av/remotion-bits",
    };
  });
}

function preserveManifestFields(nextManifest) {
  const prevPath = path.join(PRESETS_DIR, "manifest.json");
  if (!fs.existsSync(prevPath)) return nextManifest;
  try {
    const prev = JSON.parse(fs.readFileSync(prevPath, "utf8"));
    const prevById = new Map(prev.map((p) => [p.id, p]));
    return nextManifest.map((item) => {
      const old = prevById.get(item.id);
      if (!old) return item;
      return {
        ...item,
        thumbnail: old.thumbnail ?? item.thumbnail,
        parameters:
          Array.isArray(old.parameters) && old.parameters.length > 0
            ? old.parameters
            : item.parameters,
      };
    });
  } catch {
    return nextManifest;
  }
}

function writeRegistryTs(includeBits) {
  const bitsImport = includeBits
    ? `import * as Bits from "./bits";\n`
    : "";
  const bitsMapLines = includeBits
    ? BITS_PRESET_CATALOG.map(
        (item) => `  ${item.component}: Bits.${item.component} as FC,`
      ).join("\n")
    : "";
  const bitsNameLines = includeBits
    ? BITS_PRESET_CATALOG.map((item) => `  "${item.component}",`).join("\n")
    : "";

  const mapBody = [
    ...RVE_PRESET_CATALOG.map(
      (item) => `  ${item.component}: Rve.${item.component} as FC,`
    ),
    ...(bitsMapLines ? [bitsMapLines] : []),
  ].join("\n");

  const namesBody = [
    ...RVE_PRESET_CATALOG.map((item) => `  "${item.component}",`),
    ...(bitsNameLines ? [bitsNameLines] : []),
  ].join("\n");

  const registryTs = `/**
 * Auto-generated by compose-preset-bundle.cjs — do not edit manually.
 */
import type { FC } from "react";
import * as Rve from "./rve";
${bitsImport}
export const PRESET_COMPONENT_MAP: Record<string, FC> = {
${mapBody}
};

export function resolvePresetComponent(name: string): FC | undefined {
  return PRESET_COMPONENT_MAP[name];
}

export const PRESET_COMPONENT_NAMES = new Set<string>([
${namesBody}
]);
`;

  fs.writeFileSync(REGISTRY_PATH, registryTs, "utf8");
}

function writeComponentRegistry(includeBits) {
  /** @type {Record<string, { importPath: string, exportName: string }>} */
  const componentRegistry = {};
  for (const item of RVE_PRESET_CATALOG) {
    const moduleBase = item.file.replace(/\.tsx$/, "");
    componentRegistry[item.component] = {
      importPath: `./presets/rve/${moduleBase}`,
      exportName: item.component,
    };
  }
  if (includeBits) {
    for (const item of BITS_PRESET_CATALOG) {
      const moduleBase = item.file.replace(/\.tsx$/, "");
      componentRegistry[item.component] = {
        importPath: `./presets/bits/${moduleBase}`,
        exportName: item.component,
      };
    }
  }
  fs.writeFileSync(
    path.join(PRESETS_DIR, "component-registry.json"),
    `${JSON.stringify(componentRegistry, null, 2)}\n`,
    "utf8"
  );
}

function writeCategories() {
  const categories = [
    { id: "all", label: "全部", icon: "LayoutGrid" },
    { id: "background", label: "背景", icon: "Layers" },
    { id: "title", label: "文字", icon: "Type" },
    { id: "data-chart", label: "图表", icon: "BarChart3" },
    { id: "intro-outro", label: "片头片尾", icon: "Clapperboard" },
    { id: "social-media", label: "媒体", icon: "Image" },
    { id: "content", label: "动效", icon: "Sparkles" },
    { id: "transition", label: "转场", icon: "ArrowLeftRight" },
  ];
  fs.writeFileSync(
    path.join(PRESETS_DIR, "categories.json"),
    `${JSON.stringify(categories, null, 2)}\n`,
    "utf8"
  );
}

/**
 * Write merged manifest + registry from catalogs (Bits only if vendored).
 * @returns {{ includeBits: boolean, manifestCount: number }}
 */
function composePresetBundle() {
  ensureDir(PRESETS_DIR);
  ensureDir(RENDERER_DATA_DIR);

  const includeBits = bitsVendored();
  let manifest = [...buildRveManifestEntries(), ...buildBitsManifestEntries()];
  manifest = preserveManifestFields(manifest);

  fs.writeFileSync(
    path.join(PRESETS_DIR, "manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8"
  );

  writeCategories();
  writeComponentRegistry(includeBits);
  writeRegistryTs(includeBits);

  fs.copyFileSync(
    path.join(PRESETS_DIR, "manifest.json"),
    path.join(RENDERER_DATA_DIR, "manifest.json")
  );
  fs.copyFileSync(
    path.join(PRESETS_DIR, "categories.json"),
    path.join(RENDERER_DATA_DIR, "categories.json")
  );

  return { includeBits, manifestCount: manifest.length };
}

module.exports = {
  composePresetBundle,
  bitsVendored,
  BITS_PRESET_CATALOG,
  RVE_PRESET_CATALOG,
};
